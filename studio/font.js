// Returns [[x, y], ...] pixel coords (y down) for a string; advance 6 px per char.
export function textPixels(str) {
  const out = [];
  [...str.toUpperCase()].forEach((ch, i) => {
    const g = G[ch] || G['?'];
    g.forEach((row, y) => [...row].forEach((c, x) => { if (c === '#') out.push([i * 6 + x, y]); }));
  });
  return out;
}
export const textWidth = (str) => Math.max(0, str.length * 6 - 1);
